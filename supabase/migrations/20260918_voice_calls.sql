-- Ligações de voz 1x1 via WebRTC + Supabase Realtime

alter table public.mensagens
    add column if not exists chamada_id uuid,
    add column if not exists meta jsonb;

create table if not exists public.chamadas (
    id uuid primary key default gen_random_uuid(),
    tipo text not null default 'voz',
    status text not null default 'ringing',
    chamador_email text not null,
    receptor_email text not null,
    offer jsonb,
    answer jsonb,
    created_at timestamptz not null default now(),
    answered_at timestamptz,
    ended_at timestamptz,
    duracao_segundos integer not null default 0,
    ended_by text,
    updated_at timestamptz not null default now()
);

create table if not exists public.chamada_ice_candidates (
    id bigint generated by default as identity primary key,
    chamada_id uuid not null references public.chamadas(id) on delete cascade,
    remetente_email text not null,
    candidate jsonb not null,
    created_at timestamptz not null default now()
);

create index if not exists chamadas_chamador_status_idx
    on public.chamadas (chamador_email, status, created_at desc);

create index if not exists chamadas_receptor_status_idx
    on public.chamadas (receptor_email, status, created_at desc);

create index if not exists chamada_ice_chamada_idx
    on public.chamada_ice_candidates (chamada_id, id);

create index if not exists mensagens_chamada_idx
    on public.mensagens (chamada_id)
    where chamada_id is not null;

alter table public.chamadas enable row level security;
alter table public.chamada_ice_candidates enable row level security;

