create or replace function public.preparar_estado_chamada()
returns trigger
language plpgsql
as $$
begin
    new.updated_at := now();

    if new.status = 'active' and new.answered_at is null then
        new.answered_at := now();
    end if;

    if new.status in ('ended', 'cancelled', 'rejected', 'missed', 'failed') then
        if new.ended_at is null then
            new.ended_at := now();
        end if;

        if new.answered_at is not null and coalesce(new.duracao_segundos, 0) <= 0 then
            new.duracao_segundos :=
                greatest(0, floor(extract(epoch from (new.ended_at - new.answered_at)))::integer);
        end if;
    end if;

    return new;
end;
$$;

drop trigger if exists trg_preparar_estado_chamada on public.chamadas;
create trigger trg_preparar_estado_chamada
before update on public.chamadas
for each row
execute function public.preparar_estado_chamada();

create or replace function public.criar_mensagem_da_chamada()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.mensagens (
        remetente_email,
        destinatario_email,
        texto,
        tipo,
        chamada_id,
        meta
    ) values (
        new.chamador_email,
        new.receptor_email,
        '[CHAMADA]',
        'chamada',
        new.id,
        jsonb_build_object(
            'tipo_chamada', new.tipo,
            'status', new.status,
            'duracao_segundos', coalesce(new.duracao_segundos, 0),
            'chamador_email', new.chamador_email,
            'receptor_email', new.receptor_email
        )
    );

    return new;
end;
$$;

drop trigger if exists trg_criar_mensagem_da_chamada on public.chamadas;
create trigger trg_criar_mensagem_da_chamada
after insert on public.chamadas
for each row
execute function public.criar_mensagem_da_chamada();

create or replace function public.sincronizar_mensagem_da_chamada()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    update public.mensagens
       set meta = jsonb_build_object(
            'tipo_chamada', new.tipo,
            'status', new.status,
            'duracao_segundos', coalesce(new.duracao_segundos, 0),
            'chamador_email', new.chamador_email,
            'receptor_email', new.receptor_email
       )
     where chamada_id = new.id;

    return new;
end;
$$;

drop trigger if exists trg_sincronizar_mensagem_da_chamada on public.chamadas;
create trigger trg_sincronizar_mensagem_da_chamada
after update on public.chamadas
for each row
when (
    old.status is distinct from new.status
    or old.duracao_segundos is distinct from new.duracao_segundos
)
execute function public.sincronizar_mensagem_da_chamada();

