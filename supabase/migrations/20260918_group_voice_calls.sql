-- Ligações de voz em grupo (WebRTC mesh), limitadas a membros do grupo.
-- Até 15 participantes podem ficar com status "joined" ao mesmo tempo.

create table if not exists public.chamadas_grupo (
    id uuid primary key default gen_random_uuid(),
    grupo_id uuid not null references public.grupos(id) on delete cascade,
    criado_por text not null,
    status text not null default 'active'
        check (status in ('active','ended')),
    created_at timestamptz not null default now(),
    ended_at timestamptz,
    updated_at timestamptz not null default now()
);

create unique index if not exists chamadas_grupo_uma_ativa_por_grupo
    on public.chamadas_grupo (grupo_id)
    where status = 'active';

create index if not exists chamadas_grupo_grupo_status_idx
    on public.chamadas_grupo (grupo_id, status, created_at desc);

create table if not exists public.chamadas_grupo_participantes (
    chamada_id uuid not null references public.chamadas_grupo(id) on delete cascade,
    usuario_email text not null,
    status text not null default 'invited'
        check (status in ('invited','joined','rejected','left')),
    joined_at timestamptz,
    left_at timestamptz,
    updated_at timestamptz not null default now(),
    primary key (chamada_id, usuario_email)
);

create index if not exists chamadas_grupo_participantes_usuario_idx
    on public.chamadas_grupo_participantes (usuario_email, status, chamada_id);

create table if not exists public.chamadas_grupo_sinais (
    id bigint generated by default as identity primary key,
    chamada_id uuid not null references public.chamadas_grupo(id) on delete cascade,
    de_email text not null,
    para_email text not null,
    tipo text not null check (tipo in ('offer','answer','ice')),
    payload jsonb not null,
    created_at timestamptz not null default now()
);

create index if not exists chamadas_grupo_sinais_destino_idx
    on public.chamadas_grupo_sinais (chamada_id, para_email, id);

alter table public.chamadas_grupo enable row level security;
alter table public.chamadas_grupo_participantes enable row level security;
alter table public.chamadas_grupo_sinais enable row level security;

