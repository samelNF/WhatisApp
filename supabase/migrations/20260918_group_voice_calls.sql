create or replace function public.validar_participante_chamada_grupo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_grupo_id uuid;
    v_status text;
    v_total integer;
begin
    select grupo_id,status into v_grupo_id,v_status
    from public.chamadas_grupo where id=new.chamada_id;

    if v_grupo_id is null then
        raise exception 'Ligação não encontrada';
    end if;

    if not exists (
        select 1 from public.grupo_membros gm
        where gm.grupo_id=v_grupo_id
          and lower(gm.usuario_email)=lower(new.usuario_email)
    ) then
        raise exception 'Usuário não pertence ao grupo';
    end if;

    if new.status='joined' then
        if v_status <> 'active' then
            raise exception 'Ligação encerrada';
        end if;

        select count(*) into v_total
        from public.chamadas_grupo_participantes p
        where p.chamada_id=new.chamada_id
          and p.status='joined'
          and lower(p.usuario_email)<>lower(new.usuario_email);

        if v_total >= 15 then
            raise exception 'Limite de 15 participantes atingido';
        end if;

        if tg_op='INSERT' or old.status is distinct from 'joined' then
            new.joined_at := now();
        end if;
        new.left_at := null;
    elsif new.status in ('left','rejected') then
        new.left_at := now();
    end if;

    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists trg_validar_participante_chamada_grupo on public.chamadas_grupo_participantes;
create trigger trg_validar_participante_chamada_grupo
before insert or update on public.chamadas_grupo_participantes
for each row execute function public.validar_participante_chamada_grupo();

create or replace function public.encerrar_chamada_grupo_vazia()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if old.status='joined' and new.status<>'joined' then
        if not exists (
            select 1 from public.chamadas_grupo_participantes p
            where p.chamada_id=new.chamada_id
              and p.status='joined'
        ) then
            update public.chamadas_grupo
               set status='ended', ended_at=now()
             where id=new.chamada_id and status='active';
        end if;
    end if;
    return new;
end;
$$;

drop trigger if exists trg_encerrar_chamada_grupo_vazia on public.chamadas_grupo_participantes;
create trigger trg_encerrar_chamada_grupo_vazia
after update on public.chamadas_grupo_participantes
for each row execute function public.encerrar_chamada_grupo_vazia();

create or replace function public.validar_sinal_chamada_grupo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_grupo_id uuid;
    v_status text;
begin
    if lower(new.de_email)=lower(new.para_email) then
        raise exception 'Sinalização para si mesmo não é permitida';
    end if;

    select grupo_id,status into v_grupo_id,v_status
    from public.chamadas_grupo where id=new.chamada_id;

    if v_grupo_id is null or v_status<>'active' then
        raise exception 'Ligação de grupo não está ativa';
    end if;

    if not exists (
        select 1 from public.grupo_membros
        where grupo_id=v_grupo_id
          and lower(usuario_email)=lower(new.de_email)
    ) or not exists (
        select 1 from public.grupo_membros
        where grupo_id=v_grupo_id
          and lower(usuario_email)=lower(new.para_email)
    ) then
        raise exception 'Sinalização fora do grupo';
    end if;

    return new;
end;
$$;

drop trigger if exists trg_validar_sinal_chamada_grupo on public.chamadas_grupo_sinais;
create trigger trg_validar_sinal_chamada_grupo
before insert on public.chamadas_grupo_sinais
for each row execute function public.validar_sinal_chamada_grupo();

create or replace function public.sincronizar_membro_com_chamadas_ativas()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if tg_op='INSERT' then
        insert into public.chamadas_grupo_participantes (
            chamada_id, usuario_email, status, updated_at
        )
        select cg.id,new.usuario_email,'invited',now()
        from public.chamadas_grupo cg
        where cg.grupo_id=new.grupo_id
          and cg.status='active'
        on conflict (chamada_id,usuario_email) do nothing;
        return new;
    end if;

    if tg_op='DELETE' then
        update public.chamadas_grupo_participantes p
           set status='left', left_at=now(), updated_at=now()
          from public.chamadas_grupo cg
         where p.chamada_id=cg.id
           and cg.grupo_id=old.grupo_id
           and cg.status='active'
           and lower(p.usuario_email)=lower(old.usuario_email)
           and p.status in ('joined','invited');
        return old;
    end if;

    return null;
end;
$$;

drop trigger if exists trg_sincronizar_membro_chamadas_ativas on public.grupo_membros;
create trigger trg_sincronizar_membro_chamadas_ativas
after insert or delete on public.grupo_membros
for each row execute function public.sincronizar_membro_com_chamadas_ativas();

create or replace function public.limpar_sinais_chamada_grupo_encerrada()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if old.status<>'ended' and new.status='ended' then
        delete from public.chamadas_grupo_sinais where chamada_id=new.id;
    end if;
    return new;
end;
$$;

drop trigger if exists trg_limpar_sinais_chamada_grupo on public.chamadas_grupo;
create trigger trg_limpar_sinais_chamada_grupo
after update on public.chamadas_grupo
for each row execute function public.limpar_sinais_chamada_grupo_encerrada();

