create or replace function public.validar_chamada_grupo_nova()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if not exists (
        select 1 from public.grupo_membros gm
        where gm.grupo_id = new.grupo_id
          and lower(gm.usuario_email) = lower(new.criado_por)
    ) then
        raise exception 'Somente membro do grupo pode iniciar ligação';
    end if;

    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists trg_validar_chamada_grupo_nova on public.chamadas_grupo;
create trigger trg_validar_chamada_grupo_nova
before insert on public.chamadas_grupo
for each row execute function public.validar_chamada_grupo_nova();

create or replace function public.preparar_chamada_grupo_update()
returns trigger
language plpgsql
as $$
begin
    new.updated_at := now();
    if new.status = 'ended' and new.ended_at is null then
        new.ended_at := now();
    end if;
    return new;
end;
$$;

drop trigger if exists trg_preparar_chamada_grupo_update on public.chamadas_grupo;
create trigger trg_preparar_chamada_grupo_update
before update on public.chamadas_grupo
for each row execute function public.preparar_chamada_grupo_update();

create or replace function public.criar_participantes_chamada_grupo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    insert into public.chamadas_grupo_participantes (
        chamada_id, usuario_email, status, joined_at, updated_at
    )
    select
        new.id,
        gm.usuario_email,
        case when lower(gm.usuario_email)=lower(new.criado_por)
             then 'joined' else 'invited' end,
        case when lower(gm.usuario_email)=lower(new.criado_por)
             then now() else null end,
        now()
    from public.grupo_membros gm
    where gm.grupo_id = new.grupo_id
    on conflict (chamada_id, usuario_email) do nothing;

    return new;
end;
$$;

drop trigger if exists trg_criar_participantes_chamada_grupo on public.chamadas_grupo;
create trigger trg_criar_participantes_chamada_grupo
after insert on public.chamadas_grupo
for each row execute function public.criar_participantes_chamada_grupo();

